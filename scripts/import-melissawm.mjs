#!/usr/bin/env node
/**
 * Seed registry/policies/ from melissawm/open-source-ai-contribution-policies (CC0-1.0).
 *
 * Every generated entry is marked `confidence: imported`. The upstream list carries its
 * own disclaimer that the classification "is, in many cases, inadequate" — we preserve
 * that by never claiming an imported entry is verified. Verification is a manual step.
 *
 * Usage: node scripts/import-melissawm.mjs [path-to-README.md]
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from "node:fs";
import { join } from "node:path";

const SOURCE_LIST = "https://github.com/melissawm/open-source-ai-contribution-policies";
const OUT = join(import.meta.dirname, "..", "registry", "policies");
const TODAY = new Date().toISOString().slice(0, 10);

const src = process.argv[2];
const readme = src
  ? readFileSync(src, "utf8")
  : await (await fetch(`https://raw.githubusercontent.com/melissawm/open-source-ai-contribution-policies/HEAD/README.md`)).text();

const link = (cell) => {
  const m = /\[([^\]]*)\]\(([^)]+)\)/.exec(cell ?? "");
  return m ? { text: m[1].trim(), url: m[2].trim() } : null;
};
const plain = (cell) => (cell ?? "").replace(/\[([^\]]*)\]\([^)]+\)/g, "$1").trim();

const YES_NO = (v) => (/^yes$/i.test(v) ? "yes" : /^no\*$/i.test(v) ? "no*" : /^no$/i.test(v) ? "no" : null);

const STANCE = { yes: "allowed", no: "forbidden", "no*": "restricted" };
const REQ = { yes: "required", no: "not_required" };
// "no*" and unparseable values carry no usable claim -> unknown, never a guess.
const req = (v) => (v && REQ[v]) || "unknown";

/** Derive an "owner/repo" slug from a forge URL, host-qualified. */
function slugOf(url) {
  if (!url) return null;
  const m = /^https?:\/\/([^/]+)\/(?:([^/]+)\/)??([^/?#]+)\/([^/?#]+)/i.exec(url);
  const host = /^https?:\/\/([^/]+)/i.exec(url)?.[1]?.toLowerCase();
  if (!host) return null;
  const path = url.replace(/^https?:\/\/[^/]+\//i, "").split(/[?#]/)[0].split("/");
  // Forge-specific: strip the /-/ , /blob/ , /src/ , /tree/ tails.
  const known = ["github.com", "gitlab.com", "codeberg.org"];
  const isGnomeGitlab = /gitlab\./.test(host);
  if (!known.includes(host) && !isGnomeGitlab) return null;
  const owner = path[0];
  const repo = path[1];
  if (!owner || !repo || owner === "" || repo === "") return null;
  if (["orgs", "topics", "search"].includes(owner)) return null;
  return `${host}/${owner}/${repo.replace(/\.git$/, "")}`;
}

const slugify = (name) =>
  name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60);

const yamlStr = (s) => {
  const clean = String(s).replace(/\s+/g, " ").trim();
  return `"${clean.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
};

// Clear previously generated (imported) entries; hand-verified ones are kept.
mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) {
  if (!f.endsWith(".yml")) continue;
  const body = readFileSync(join(OUT, f), "utf8");
  if (/^confidence:\s*imported\s*$/m.test(body)) unlinkSync(join(OUT, f));
}
const kept = new Set(readdirSync(OUT).filter((f) => f.endsWith(".yml")).map((f) => f.replace(/\.yml$/, "")));

let written = 0, skipped = 0, keptCount = 0;
for (const line of readme.split("\n")) {
  if (!line.includes("|")) continue;
  const cells = line.split("|").map((c) => c.trim());
  if (cells.length < 6) continue;
  const project = link(cells[0]);
  const policy = link(cells[1]);
  if (!project || !policy) continue;              // header, separator, prose
  if (/^project$/i.test(project.text)) continue;

  const allowed = YES_NO(plain(cells[2]));
  if (!allowed) { skipped++; continue; }          // "?" or "-" — no usable claim

  const key = slugify(project.text);
  if (kept.has(key)) { keptCount++; continue; }   // never clobber a verified entry

  const disclosure = YES_NO(plain(cells[3]));
  const copyright = YES_NO(plain(cells[4]));
  const hitl = YES_NO(plain(cells[5]));
  const notes = plain(cells[6] ?? "").replace(/^-$/, "");

  const repos = [...new Set([slugOf(project.url), slugOf(policy.url)].filter(Boolean))];

  const out = [
    "# Generated by scripts/import-melissawm.mjs — do not hand-edit.",
    "# To correct this entry: verify it against the primary source, fix the fields,",
    "# and change `confidence` to `verified`. The importer then leaves it alone.",
    "version: 1",
    `project: ${yamlStr(project.text)}`,
    `policy_url: ${yamlStr(policy.url)}`,
    `homepage: ${yamlStr(project.url)}`,
    repos.length ? `repos:\n${repos.map((r) => `  - ${yamlStr(r)}`).join("\n")}` : null,
    `stance: ${STANCE[allowed]}`,
    `disclosure: ${req(disclosure)}`,
    `human_in_the_loop: ${req(hitl)}`,
    copyright === "yes" || copyright === "no"
      ? `copyright_statement: ${copyright === "yes"}`
      : "copyright_statement: null",
    notes ? `notes: ${yamlStr(notes)}` : null,
    `sources:\n  - ${yamlStr(policy.url)}\n  - ${yamlStr(SOURCE_LIST)}`,
    "confidence: imported",
    `updated: ${TODAY}`,
  ].filter(Boolean).join("\n") + "\n";

  writeFileSync(join(OUT, `${key}.yml`), out);
  written++;
}
console.log(`imported: ${written}  kept(verified): ${keptCount}  skipped(no usable stance): ${skipped}`);
